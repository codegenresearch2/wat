def test_inspect_nested_dict():
    output = inspect_format({
        'a': {
            'b': {
                'values': [2,5,3],
            },
            "empty_dict": {},
            "empty_list": [],
            40: None,
            None: 42,
        },
    }, short=True)
    expected_output = """
value: {
    'a': {
        'b': {
            'values': [
                2,
                5,
                3,
            ],
        },
        'empty_dict': {},
        'empty_list': [],
        40: None,
        None: 42,
    },
}
type: dict
len: 1
"""
    assert strip_ansi_colors(output).strip() == expected_output.strip()


